# Assignment Operators
# | Operator | Example | Same As      |
# | -------- | ------- | ------------ |
# | =        | x = 5   | Assign value |
# | +=       | x += 3  | x = x + 3    |
# | -=       | x -= 3  | x = x - 3    |
# | *=       | x *= 3  | x = x * 3    |
# | /=       | x /= 3  | x = x / 3    |
# | //=      | x //= 3 | x = x // 3   |
# | %=       | x %= 3  | x = x % 3    |
# | **=      | x **= 2 | x = x ** 2   |

x = 10

x += 5
print(x)

x -= 3
print(x)

x *= 2
print(x)

x /= 4
print(x)