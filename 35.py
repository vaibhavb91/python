# Range
# range(start, stop, step)
# start → where to start
# stop → where to stop (not included)
# step → how much to increase/decrease
# range(5) means 0 to 4, not 0 to 5
for i in range(5):
    print(i)

print("next")

for i in range(1, 6):
    print(i)

print("======")
for i in range(2, 11, 2):
    print(i)